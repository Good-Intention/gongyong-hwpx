def split_lines(chs):
    """강제 줄 바꿈(\\n)으로 나눈 글자 묶음들."""
    out, cur = [], []
    for c in chs:
        if c[0] == "\n":
            out.append(cur)
            cur = []
        else:
            cur.append(c)
    out.append(cur)
    return out

